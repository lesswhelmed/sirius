const { withAppDelegate } = require("@expo/config-plugins");

// Native cookie-jar hardening (iOS).
//
// Auth in this app is cookie-managed ENTIRELY in JS: @better-auth/expo stores the
// session cookie in SecureStore and attaches it as a manual `Cookie` header with
// `credentials:"omit"`, so its own requests bypass the native URL-loading system's
// cookie jar. But anything that does NOT set credentials:"omit" — notably the
// realtime SSE channel (react-native-sse → XMLHttpRequest, whose `withCredentials`
// defaults to TRUE → iOS `HTTPShouldHandleCookies = YES`) — pulls cookies from
// iOS's shared `HTTPCookieStorage`. That native jar captures a `Set-Cookie` once
// and then re-sends a STALE `better-auth.session_token` on every such request,
// overriding the fresh manual header. The server validates the stale token and
// returns 401 (seen as repeating 401s on /api/app/posts/stream), and because
// re-login uses credentials:"omit" the jar never refreshes — only a reinstall
// cleared it. See docs / memory: mobile-unauthorized-stale-cookie.
//
// Fix: at launch, empty the shared cookie storage and set its accept policy to
// `.never`, so RN's NSURLSession (which uses the shared storage by default) can
// neither send a stale cookie nor store a new one. The JS layer remains the sole
// owner of the session cookie. ios/ is gitignored + regenerated by `expo
// prebuild`, so this mod must re-apply on every prebuild.
const SENTINEL = "Sirius: native cookie-jar hardening";

const HARDENING_SWIFT = `    // ${SENTINEL} — see plugins/with-cookie-jar-hardening.js
    HTTPCookieStorage.shared.cookieAcceptPolicy = .never
    if let staleCookies = HTTPCookieStorage.shared.cookies {
      for cookie in staleCookies { HTTPCookieStorage.shared.deleteCookie(cookie) }
    }
`;

const withCookieJarHardening = (config) =>
  withAppDelegate(config, (cfg) => {
    if (cfg.modResults.language !== "swift") {
      throw new Error(
        "[with-cookie-jar-hardening] expected a Swift AppDelegate; got " +
          cfg.modResults.language,
      );
    }
    let contents = cfg.modResults.contents;
    if (contents.includes(SENTINEL)) return cfg; // idempotent

    // Run the hardening as the first statement of didFinishLaunchingWithOptions,
    // before the React Native factory (and thus any network) starts. Anchor on
    // the factory-delegate line that opens that method's body.
    const anchor = "    let delegate = ReactNativeDelegate()";
    if (!contents.includes(anchor)) {
      throw new Error(
        "[with-cookie-jar-hardening] could not find the AppDelegate launch anchor; " +
          "the Expo AppDelegate template changed — update this plugin.",
      );
    }
    contents = contents.replace(anchor, `${HARDENING_SWIFT}${anchor}`);
    cfg.modResults.contents = contents;
    return cfg;
  });

module.exports = withCookieJarHardening;
