// Shared types for the classifier. Pure data only — no DOM `File`, no RN asset
// type, no React. See index.ts for the host-agnostic contract.

// IngestKind is the FIXED 6-kind submission enum. It is duplicated here as a
// string-literal union (rather than importing `@repo/db`) so this package stays
// dependency-light and host-agnostic: `@repo/db` pulls in Prisma + a Node pg
// adapter, which must never reach the mobile bundle. The `assertIngestKind`
// compile-time check below guarantees this union stays byte-identical to the
// `IngestKind` defined in packages/db/src/ingest.ts (lines 8-14). If the two
// drift, the assertion lines fail to type-check and this file won't build.
export type IngestKind =
  | "url"
  | "image"
  | "note"
  | "video"
  | "audio"
  | "document";

// Cosmetic platform sub-label, present only when kind === "url". Re-detected
// server-side by the worker — never trusted for routing (see index.ts header).
export type PlatformLabel =
  | "repository"
  | "instagram"
  | "x"
  | "youtube"
  | "link";

// Host-neutral file descriptor. Web wraps a DOM `File`
// ({ name, mimeType: file.type, size: file.size, ref: file }); mobile wraps an
// RN asset ({ name, mimeType: asset.mimeType ?? asset.type, size, ref: asset }).
// The pure core only ever reads name/mimeType/size — `ref` is an opaque handle
// the host keeps to retrieve the real bytes at submit time (keyed by item id).
export interface FileDescriptor {
  name: string;
  mimeType: string;
  size: number;
  // Opaque host handle (DOM File, RN asset, blob, uri object). The core never
  // touches it; it is carried through so the host can map item -> real bytes.
  ref?: unknown;
}

// One inline validation problem. `critical` blocks submit (the action button is
// disabled while any tray card has a critical error); `warn` never blocks.
export interface InlineError {
  field: "url" | "file" | "note";
  // Stable machine code (see VALIDATION codes in index.ts).
  code:
    | "url_invalid"
    | "url_suspicious"
    | "note_empty"
    | "file_unsupported"
    | "file_too_large"
    | "duplicate";
  message: string;
  severity: "warn" | "critical";
}

// Backwards-compatible alias for the design-doc name. Identical shape.
export type ClassifyError = InlineError;

// One classified tray item. Exactly one of { url, text, file } is populated and
// matches `kind`:
//   - kind "url"      -> url set, platform set
//   - kind "note"     -> text set
//   - kind image/video/audio/document -> file set
// `content` is a display-ready string mirror of whichever payload is set (the
// URL, the note text, or the file name) so hosts can render a card without a
// switch. `displayTag` is the short mono tag shown on the card ("Link"/"Photo"/…).
export interface ClassifiedItem {
  // Stable per-item id. Generated by the classifier (crypto.randomUUID); the
  // host uses it to key its file-handle registry and to address edits/removes.
  id: string;
  kind: IngestKind;
  platform?: PlatformLabel;
  displayTag: string;
  content: string;
  url?: string;
  text?: string;
  file?: FileDescriptor;
  // [] / undefined = clean. `errors` is the canonical field; `error` is a
  // convenience getter populated to the FIRST error for hosts that only render
  // one. Both are kept in sync by the classifier helpers.
  errors: InlineError[];
  error?: InlineError;
}

// ── Compile-time guard: this union must equal the db enum ────────────────────
// `@repo/db` is NOT imported at runtime (see comment on IngestKind above), but
// we import its type here ONLY for this assertion. A type-only import is erased
// by the compiler and never lands in the bundle. If db's IngestKind changes,
// one of these two lines stops type-checking and the build breaks loudly.
import type { IngestKind as DbIngestKind } from "@repo/db";

type AssertEqual<A, B> = [A] extends [B]
  ? [B] extends [A]
    ? true
    : never
  : never;

// If either direction fails, `_assertIngestKindMatchesDb` resolves to `never`
// and the `const … = true` assignment errors — a compile-time fence.
const _assertIngestKindMatchesDb: AssertEqual<IngestKind, DbIngestKind> = true;
// Reference it so noUnusedLocals doesn't complain.
void _assertIngestKindMatchesDb;
