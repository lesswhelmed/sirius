#!/usr/bin/env bun
// Smart generator for the local `.env.production` mirror used by the deploy
// scripts and as the template for the server `.env`. It NEVER overwrites an
// existing `.env.production` — if one is present it prints a notice and exits 0
// so the operator can safely keep their filled-in secrets.
//
// Run from the repo root: `bun run env:production`.

import { randomBytes } from "node:crypto";
import { existsSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const ROOT = resolve(import.meta.dir, "..");
const ENV_PATH = resolve(ROOT, ".env.production");

function color(code: number, text: string): string {
  return `\x1b[${code}m${text}\x1b[0m`;
}
const green = (s: string) => color(32, s);
const yellow = (s: string) => color(33, s);
const bold = (s: string) => color(1, s);
const dim = (s: string) => color(90, s);

// Generated, non-secret-but-unique tokens. Safe to pre-fill so the file is
// usable immediately; rotate before going live if desired.
function hexToken(): string {
  return randomBytes(32).toString("hex");
}

function template(): string {
  const ingestToken = hexToken();
  const revalidateToken = hexToken();
  return `# Generated by scripts/create-production-env.ts — local production mirror.
# This file is gitignored. Copy it to the server as /home/deploy/apps/sirius/.env
# after replacing every <...> placeholder with a real value.

# ─── Deploy orchestration (read by scripts/deploy-remote.sh) ────────────────
DEPLOY_APP_NAME=sirius
DEPLOY_BRANCH=main
DEPLOY_HOST=172.239.45.200
DEPLOY_SSH_KEY=~/.ssh/id_copt_dev_v1
DEPLOY_APP_DIR=/home/deploy/apps/sirius
DEPLOY_VERIFY_URL=https://lesswhelmed.com

# ─── Database (create a dedicated sirius db/user on the server Postgres) ─────
DATABASE_URL=postgresql://sirius:<password>@127.0.0.1:5432/sirius

# ─── Auth (Better Auth) ─────────────────────────────────────────────────────
# Generate with: openssl rand -base64 32
BETTER_AUTH_SECRET=<openssl_rand_base64_32>
BETTER_AUTH_URL=https://lesswhelmed.com
NEXT_PUBLIC_BETTER_AUTH_URL=https://lesswhelmed.com
# Production MUST trust the mobile deep-link scheme or Expo auth callbacks fail.
AUTH_TRUSTED_ORIGINS=siriusapp://

# ─── Mobile (Expo) ──────────────────────────────────────────────────────────
# Build-time profiles in apps/mobile/eas.json already set this for EAS builds;
# kept here so the value is documented in one place.
EXPO_PUBLIC_AUTH_BASE_URL=https://lesswhelmed.com

# ─── Email (Resend) ─────────────────────────────────────────────────────────
RESEND_API_KEY=<resend_api_key>
RESEND_FROM_EMAIL=<verified_sender@lesswhelmed.com>

# ─── Ingest pipeline ────────────────────────────────────────────────────────
# Pre-generated; rotate if you want. Used by bearer-token ingest clients.
INGEST_TOKEN=${ingestToken}
INGEST_STAGING_DIR=/home/deploy/data/sirius/ingest-staging
INGEST_POLL_INTERVAL_MS=5000
SIGHT_IMAGE_DIR=/home/deploy/apps/sirius/apps/web/public/sight
SOCIAL_IMAGE_DIR=/home/deploy/apps/sirius/apps/web/public/social

# ─── Worker → web cache invalidation ────────────────────────────────────────
# Shared secret; the worker sends it as Bearer to the revalidate endpoint.
REVALIDATE_TOKEN=${revalidateToken}
WEB_REVALIDATE_URL=https://lesswhelmed.com/api/internal/revalidate

# ─── AI (Gemini) ────────────────────────────────────────────────────────────
GEMINI_API_KEY=<gemini_api_key>
AI_MODEL=gemini-2.5-flash
AI_TEMPERATURE=0.7
EMBEDDING_MODEL=gemini-embedding-001

# ─── Instagram ingest (optional, paid Apify plan) ───────────────────────────
APIFY_TOKEN=
INSTAGRAM_ACTOR_ID=shu8hvrXbJbY3Eb9W
INSTAGRAM_MAX_ITEMS=1
INSTAGRAM_WAIT_SECS=120

# ─── YouTube ingest (optional) ──────────────────────────────────────────────
YOUTUBE_DATA_API_KEY=
YOUTUBE_AI_MODEL=gemini-2.5-pro
YOUTUBE_CHUNK_SECONDS=2700
YOUTUBE_CHUNK_OVERLAP_SECONDS=60
YOUTUBE_CHUNK_PARALLEL=2
`;
}

function main(): void {
  if (existsSync(ENV_PATH)) {
    console.log(
      `${yellow("·")} ${bold(".env.production")} ${dim("already exists — leaving it untouched.")}`
    );
    console.log(
      dim(
        "  Delete it manually first if you want a fresh template regenerated."
      )
    );
    return;
  }

  writeFileSync(ENV_PATH, template(), { mode: 0o600 });
  console.log(`${green("✓")} ${bold("Created .env.production")} ${dim(`(${ENV_PATH})`)}`);
  console.log("");
  console.log(bold("Next:"));
  console.log(`  ${dim("1.")} Replace every <...> placeholder with a real value.`);
  console.log(`  ${dim("2.")} Copy it to the server: /home/deploy/apps/sirius/.env`);
  console.log(`  ${dim("3.")} bun run deploy`);
}

main();
